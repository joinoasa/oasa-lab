#!/usr/bin/env bash
# cloudflared: the tunnel that exposes ONLY the job service (two hostnames, fixed paths). Needs your Cloudflare account.
. "$(dirname "$0")/lib.sh"
need_root; check_os
: "${MCP_HOSTNAME:=}"
: "${API_HOSTNAME:=}"
[ -n "$MCP_HOSTNAME" ] || die "set MCP_HOSTNAME (and API_HOSTNAME) in deploy/setup.env, e.g. lab-mcp.yourdomain.com"

say "cloudflared from Cloudflare's apt repository"
if [ ! -f /usr/share/keyrings/cloudflare-main.gpg ]; then
  run install -m 0755 -d /usr/share/keyrings
  if [ "$DRY_RUN" = 1 ]; then note "DRY: would download https://pkg.cloudflare.com/cloudflare-main.gpg"; else
    tmp="$(mktemp)"; curl -fsSL -o "$tmp" https://pkg.cloudflare.com/cloudflare-main.gpg
    gpg --batch --show-keys --with-fingerprint "$tmp"
    install -m 0644 "$tmp" /usr/share/keyrings/cloudflare-main.gpg; rm -f "$tmp"
  fi
fi
write_file /etc/apt/sources.list.d/cloudflared.sources 0644 root:root <<EOF
Types: deb
URIs: https://pkg.cloudflare.com/cloudflared
Suites: any
Components: main
Signed-By: /usr/share/keyrings/cloudflare-main.gpg
EOF
run apt-get update
pkg_install cloudflared

say "Tunnel (needs you)"
if [ ! -d /etc/cloudflared ] || ! ls /etc/cloudflared/*.json >/dev/null 2>&1; then
  owner "Log in to Cloudflare and make the tunnel (opens a browser link; run as your normal user, not root):"
  note "  cloudflared tunnel login"
  note "  cloudflared tunnel create oasa-lab"
  note "  cloudflared tunnel route dns oasa-lab $MCP_HOSTNAME"
  [ -z "$API_HOSTNAME" ] || note "  cloudflared tunnel route dns oasa-lab $API_HOSTNAME"
  note "Then copy the tunnel credentials into place and run this script again:"
  note "  sudo install -d -m 0750 /etc/cloudflared && sudo install -m 0600 ~/.cloudflared/<TUNNEL_ID>.json /etc/cloudflared/"
  exit 0
fi
TUNNEL_ID="$(basename "$(ls /etc/cloudflared/*.json | head -1)" .json)"

say "Tunnel config for $TUNNEL_ID"
if [ -n "$API_HOSTNAME" ]; then
  api_block="  - hostname: $API_HOSTNAME
    path: ^/(api/.*|healthz)\$
    service: http://127.0.0.1:8742
    originRequest:
      httpHostHeader: $API_HOSTNAME"
else api_block=""; fi
write_file /etc/cloudflared/config.yml 0644 root:root <<EOF
# Generated by 06-cloudflared.sh. Only the job service, only these paths. Everything else: 404.
tunnel: $TUNNEL_ID
credentials-file: /etc/cloudflared/$TUNNEL_ID.json

ingress:
  - hostname: $MCP_HOSTNAME
    path: ^/(mcp|authorize|token|register|revoke|healthz|oauth/.*|\.well-known/.*)\$
    service: http://127.0.0.1:8742
    originRequest:
      httpHostHeader: $MCP_HOSTNAME
$api_block
  - service: http_status:404
EOF
run cloudflared --config /etc/cloudflared/config.yml tunnel ingress validate
run cloudflared --config /etc/cloudflared/config.yml service install
run systemctl enable --now cloudflared

say "Done"
owner "In Cloudflare Zero Trust > Access controls > Applications: add a Self-hosted application for ${API_HOSTNAME:-your API hostname} with one policy: Allow, Emails, your email. Copy its Application Audience (AUD) tag and your team domain into [cloudflare_access] in /etc/oasa-lab/service.toml."
owner "Do NOT put an Access policy on $MCP_HOSTNAME: Claude's servers cannot pass a browser login. The service does its own sign-in there (GitHub, owner only)."
note "Then add the connector in Claude: https://$MCP_HOSTNAME/mcp   (see docs/remote-lab.md)"
